def rows(character):
    import unicodedata
    if character == '\u00a0': return [0] * 8
    if character == 'œ': return [0,0,0,0x3C,0x4A,0x5E,0x48,0x3E]
    if character == '¡': return [0,0x10,0,0x10,0x10,0x10,0x10,0x10]
    if character in KANA: return [0] + [value << 1 for value in KANA[character]]
    if character in GLYPHS:
        values = bytes.fromhex(GLYPHS[character])
        return [0] + [value << 2 for value in values]
    parts = unicodedata.normalize('NFD', character)
    if len(parts) == 2 and parts[0] in GLYPHS:
        values = list(bytes.fromhex(GLYPHS[parts[0]]))
        mark = {'\u0301':[2,4], '\u0300':[8,4], '\u0302':[4,10],
                '\u0303':[13,22], '\u0308':[10,0]}.get(parts[1])
        if mark:
            # Keep a six-row capital, or the lowercase's five-row body.
            body = [values[i] for i in (0,1,2,3,4,6)] if parts[0].isupper() else [0]+values[2:]
            return [value << 2 for value in mark + body]
        if parts[1] == '\u0327':
            return [value << 2 for value in ([0]+values[2:]+[4,8])]
    raise ValueError(f'No authored glyph for {character!r} (U+{ord(character):04X})')
