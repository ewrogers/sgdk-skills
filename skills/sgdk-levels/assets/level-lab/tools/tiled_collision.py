#!/usr/bin/env python3
"""Export a finite Tiled CSV collision layer as a row-major ROM bitset."""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import xml.etree.ElementTree as ET


@dataclass(frozen=True)
class Collision:
    columns: int
    rows: int
    cell: int
    bits: bytes


def integer(node, name, minimum=1):
    try:
        value = int(node.get(name, ""))
    except ValueError as error:
        raise ValueError(f"<{node.tag}> needs an integer {name}") from error
    if value < minimum:
        raise ValueError(f"<{node.tag}> {name} must be at least {minimum}")
    return value


def read_collision(path, layer_name="Collision"):
    root = ET.parse(path).getroot()
    if root.tag != "map" or root.get("orientation") != "orthogonal" or root.get("infinite", "0") != "0":
        raise ValueError("Use a finite orthogonal map; infinite/isometric maps need a different importer")
    columns, rows = integer(root, "width"), integer(root, "height")
    cell = integer(root, "tilewidth")
    if cell != 16 or integer(root, "tileheight") != cell:
        raise ValueError("This exporter supports square 16-pixel cells")
    if columns * cell > 32767 or rows * cell > 32767 or columns * rows > 1048576:
        raise ValueError("Map exceeds this exporter's signed-coordinate or cell-count bounds")
    # MAP uses these files too. Fail early on stale references instead of
    # silently exporting occupancy for an incomplete project.
    ranges = []
    for reference in root.findall("tileset"):
        first = integer(reference, "firstgid")
        tileset = reference
        source = reference.get("source")
        if source:
            tileset = ET.parse(Path(path).parent / source).getroot()
        count = integer(tileset, "tilecount")
        ranges.append((first, first + count))
    ranges.sort()
    if not ranges or any(left[1] > right[0] for left, right in zip(ranges, ranges[1:])):
        raise ValueError("Tileset GID ranges must exist and must not overlap")
    layers = [layer for layer in root.iter("layer") if layer.get("name") == layer_name]
    if len(layers) != 1 or layers[0] not in list(root):
        raise ValueError(f"Expected exactly one top-level tile layer named {layer_name!r}")
    layer = layers[0]
    if integer(layer, "width") != columns or integer(layer, "height") != rows:
        raise ValueError("Collision layer dimensions must match the map")
    for key in ["x", "y", "offsetx", "offsety"]:
        if float(layer.get(key, "0")) != 0:
            raise ValueError("Collision layer offsets must be zero")
    data = layer.find("data")
    if data is None or data.get("encoding") != "csv" or data.get("compression") or list(data):
        raise ValueError("Save Collision as uncompressed CSV tile data")
    tokens = re.split(r"\s*,\s*", (data.text or "").strip())
    if len(tokens) != columns * rows:
        raise ValueError("Collision CSV cell count does not match the map dimensions")
    bits = bytearray((columns * rows + 7) // 8)
    for index, token in enumerate(tokens):
        try:
            gid = int(token)
        except ValueError as error:
            raise ValueError(f"Invalid collision GID at cell {index}") from error
        if gid < 0 or gid > 0xFFFFFFFF or gid & 0x30000000:
            raise ValueError(f"Unsupported diagonal/hex rotation flags at cell {index}")
        base = gid & 0x0FFFFFFF
        if gid and not base:
            raise ValueError(f"Empty collision tile has transform flags at cell {index}")
        if base and not any(first <= base < last for first, last in ranges):
            raise ValueError(f"Unknown collision GID {base} at cell {index}")
        if base:
            bits[index // 8] |= 1 << (index % 8)
    return Collision(columns, rows, cell, bytes(bits))


def export(data, header, source):
    header = Path(header)
    source = Path(source)
    header.parent.mkdir(parents=True, exist_ok=True)
    source.parent.mkdir(parents=True, exist_ok=True)
    # This helper owns only these generated outputs. It never rewrites TMX/TSX.
    header.write_text(
        '/* Generated by tiled_collision.py; edit the TMX instead. */\n'
        '#ifndef LEVEL_DATA_H\n#define LEVEL_DATA_H\n#include "world.h"\n'
        f'enum {{ LEVEL_COLUMNS = {data.columns}, LEVEL_ROWS = {data.rows}, LEVEL_CELL = {data.cell} }};\n'
        'extern const WorldMap level_collision;\n#endif\n', encoding="utf-8")
    lines = [", ".join(f"0x{b:02X}" for b in data.bits[i:i+16]) for i in range(0, len(data.bits), 16)]
    source.write_text(
        '/* Generated by tiled_collision.py; edit the TMX instead. */\n'
        '#include "level_data.h"\nstatic const u8 occupancy[] = {\n    '
        + ",\n    ".join(lines) + '\n};\n'
        'const WorldMap level_collision = { LEVEL_COLUMNS, LEVEL_ROWS, LEVEL_CELL, occupancy };\n',
        encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("map", type=Path)
    parser.add_argument("--layer", default="Collision")
    parser.add_argument("--header", type=Path, default=Path("inc/level_data.h"))
    parser.add_argument("--source", type=Path, default=Path("src/level_data.c"))
    args = parser.parse_args()
    try:
        data = read_collision(args.map, args.layer)
        export(data, args.header, args.source)
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, f"Collision import failed: {error}\n")
    print(f"Collision: {data.columns}x{data.rows} cells, {len(data.bits):,} ROM bytes")


if __name__ == "__main__":
    main()
