#!/usr/bin/env python3
"""Prepare an ignored Sound Lab header for automatic PAL/NTSC emulator tests."""
import argparse
import os
from pathlib import Path
import re


MARKER = "/* Generated by Sound Lab region_header.py. */\n"


def prepare(region, sdk, project):
    source = Path(sdk) / "src/boot/rom_head.c"
    destination = Path(project) / "src/boot/rom_head.c"
    original = source.read_text(encoding="utf-8")
    text = original
    match = re.search(r'"([JUE ]{16})"\s*\n\s*};\s*$', text)
    if match is None:
        raise ValueError("Selected SGDK header has an unfamiliar region field; inspect it before adapting")
    regions = {"ntsc": "U", "pal": "E", "auto": "JUE"}
    code = regions[region].ljust(16)
    text = text[:match.start(1)] + code + text[match.end(1):]
    if destination.exists():
        existing = destination.read_text(encoding="utf-8")
        if existing != original and not existing.startswith(MARKER):
            raise ValueError("Project already has a custom ROM header; use a disposable copy of Sound Lab")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(MARKER + text, encoding="utf-8")
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("region", choices=["ntsc", "pal", "auto"])
    parser.add_argument("--sdk", type=Path, default=Path(os.environ.get("GDK", "/opt/sgdk")))
    parser.add_argument("--project", type=Path, default=Path.cwd())
    args = parser.parse_args()
    try:
        output = prepare(args.region, args.sdk, args.project)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Region header failed: {error}\n")
    print(f"Prepared {args.region} header: {output}")


if __name__ == "__main__":
    main()
